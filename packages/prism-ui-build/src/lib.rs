//! # prism-ui-build
//!
//! Compile-time codegen for `.prui` files. Each consumer crate
//! calls `prism_ui_build::compile("ui/app.prui")` from its
//! `build.rs`; the generated Rust module is emitted into `OUT_DIR`
//! and brought into scope via `include!(concat!(env!("OUT_DIR"),
//! "/<file>.rs"))`.
//!
//! See ADR-008 and `docs/dev/clay-migration-plan.md` §4.6.
//!
//! Phase 2 wiring: parses the source through
//! `prism_core::language::prism_ui::parse`, validates it at build
//! time, then emits a thin Rust module that exposes
//!
//! - `SOURCE`: the original `.prui` text for the runtime
//!   interpret path,
//! - `COMPONENT_NAMES`: every `<component name="...">` in document
//!   order,
//! - `nodes()`: a runtime helper that re-parses `SOURCE` through
//!   `prism_ui_runtime::interpret::interpret` and returns a
//!   `Vec<prism_ui_runtime::layout::Node>` ready for `Surface::new`.
//!
//! Re-parsing at runtime keeps the source canonical (per plan §4.6 —
//! `.prui` is the source of truth, the AST is derived) and lets
//! live edits use the same path. Build-time validation guarantees
//! `nodes()` cannot panic on a parse error in shipped binaries.

